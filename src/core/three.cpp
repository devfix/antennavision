    void Container::export_to_javascript(std::filesystem::path const& p) const
    {
        std::ofstream ofs(p);
        ofs << "// This file was automatically generated by " << APPLICATION_NAME << " v." << convert::string_from_version(APPLICATION_VERSION) << ". Do not edit!\n";
        ofs << "const configObjects = [\n";
        for (auto const& object : objects) { ofs << object.dump(2) << ",\n"; }
        ofs << "];\n";
    }

    json make_line(std::vector<Pos> const& points, double const width, Color const color)
    {
        json js;
        std::vector<double> points_flat;
        points_flat.reserve(points.size() * 3);
        for (auto const point : points)
        {
            points_flat.push_back(point.x);
            points_flat.push_back(point.y);
            points_flat.push_back(point.z);
        }
        js["type"] = "line";
        js["color"] = hex_string_from_color(color);
        js["width"] = width;
        js["points"] = points_flat;
        return js;
    }

    json make_line(Pos pos_a, Pos pos_b, double const width, Color const color) { return make_line({pos_a, pos_b}, width, color); }

    json make_sphere(Pos const& pos, double const radius, Color const color, std::uint16_t const segments_width, std::uint16_t const segments_height)
    {
        json js;
        js["type"] = "sphere";
        js["color"] = hex_string_from_color(color);
        js["radius"] = radius;
        js["pos"] = pos.toNdArray().toStlVector();
        constexpr Quaternion quat{}; // unity quaternion
        js["quat"] = {quat.i(), quat.j(), quat.k(), quat.s()};
        js["width_segments"] = segments_width;
        js["height_segments"] = segments_height;
        return js;
    }

    json make_cylinder(Pos const& pos_start,
        Pos const& pos_end,
        double const radius_start,
        double const radius_end,
        Color const color,
        std::uint16_t segments_radial)
    {
        json js;
        js["type"] = "cylinder";
        js["color"] = hex_string_from_color(color);
        auto const pos_center = (pos_start + pos_end) / 2.0;
        auto const direction = pos_end - pos_start;
        js["radius_top"] = radius_end;
        js["radius_bottom"] = radius_start;
        js["height"] = direction.norm();
        js["pos"] = pos_center.toNdArray().toStlVector();

        // default orientation of a cylinder in THREE is (0,1,0)
        auto const quat = math::quaternion_from_directions(Pos(0.0, 1.0, 0.0), direction);
        js["quat"] = {quat.i(), quat.j(), quat.k(), quat.s()};
        js["radial_segments"] = segments_radial;
        return js;
    }

    json make_cone(Pos const& pos_start, Pos const& pos_end, double const radius, Color const color, std::uint16_t segments_radial)
    {
        json js;
        js["type"] = "cone";
        js["color"] = hex_string_from_color(color);
        auto const pos_center = (pos_start + pos_end) / 2.0;
        auto const direction = pos_end - pos_start;
        js["radius"] = radius;
        js["height"] = direction.norm();
        js["pos"] = pos_center.toNdArray().toStlVector();

        // default orientation of a cone in THREE is (0,1,0)
        auto const quat = math::quaternion_from_directions(Pos(0.0, 1.0, 0.0), direction);
        js["quat"] = {quat.i(), quat.j(), quat.k(), quat.s()};
        js["radial_segments"] = segments_radial;
        return js;
    }

    json make_plane(Pos const& pos, Pos const& dir_target, double const width, double const height, double const angle, Color const color)
    {
        json js;
        js["type"] = "plane";
        js["color"] = hex_string_from_color(color);
        js["width"] = width;
        js["height"] = height;
        js["pos"] = pos.toNdArray().toStlVector();

        // default orientation of a plane in THREE is (0,0,1)
        auto const quat = Quaternion(dir_target, angle) * math::quaternion_from_directions(Pos(0.0, 0.0, 1.0), dir_target);
        js["quat"] = {quat.i(), quat.j(), quat.k(), quat.s()};
        return js;
    }

    std::vector<json>
    create_arrow(Pos const& pos_start, Pos const& pos_end, double const len_head, double const radius_line, double const radius_head, Color const color)
    {
        auto const pos_contact = pos_end + (pos_start - pos_end).normalize() * len_head;
        return {make_cylinder(pos_start, pos_contact, radius_line, radius_line, color), make_cone(pos_contact, pos_end, radius_head, color)};
    }

