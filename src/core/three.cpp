    [[nodiscard]] constexpr std::string hex_string_from_color(Color const color) { return std::format("#{:06x}", static_cast<std::uint32_t>(color)); }

    template <typename T, typename... Args>
    size_t total_size(const std::vector<T>& first, const Args&... rest)
    { return first.size() + (rest.size() + ...); }

    template <typename T, typename... Args>
    std::vector<T> concat_and_destroy(std::vector<T>&& first, Args&&... rest)
    {
        first.reserve(total_size(first, rest...));
        (..., first.insert(first.end(), std::make_move_iterator(rest.begin()), std::make_move_iterator(rest.end())));
        return std::move(first);
    }
